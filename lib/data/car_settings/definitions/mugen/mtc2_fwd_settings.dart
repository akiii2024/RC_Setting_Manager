List<SettingItem> _damperSettings(String end, String label) {
  final side = end == 'front' ? 'Front' : 'Rear';
  final category = '${end}Damper';
  return [
    textSetting(
      key: '${end}Piston',
      category: category,
      label: '$label ピストン',
      labelEn: '$side Piston',
    ),
    textSetting(
      key: '${end}ShockCase',
      category: category,
      label: '$label ダンパーケース',
      labelEn: '$side Shock Case',
    ),
    textSetting(
      key: '${end}ShockOil',
      category: category,
      label: '$label ダンパーオイル',
      labelEn: '$side Shock Oil',
    ),
    textSetting(
      key: '${end}Spring',
      category: category,
      label: '$label スプリング',
      labelEn: '$side Spring',
    ),
    // 長さと取り付け位置の範囲・刻みは x4_24_settings.dart のダンパー長・マウントシムに準拠。
    numberSetting(
      key: '${end}DamperLength',
      category: category,
      label: '$label ダンパー長',
      labelEn: '$side Shock Length',
      unit: 'mm',
      min: 0,
      max: 50,
      step: 0.5,
      defaultValue: '8',
    ),
    numberSetting(
      key: '${end}ShockPosition',
      category: category,
      label: '$label ダンパー取り付け位置',
      labelEn: '$side Shock Position',
      unit: 'mm',
      min: 0,
      max: 10,
      step: 0.5,
      defaultValue: '0',
    ),
  ];
}

