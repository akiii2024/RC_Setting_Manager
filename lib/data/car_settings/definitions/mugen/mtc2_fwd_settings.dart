List<SettingItem> _endSettings({
  required String end,
  required String label,
  required List<String> armPositions,
  required List<String> casterOptions,
}) =>
    [
      // シートに範囲がない車高・キャンバー・トー・ダウンストップ・アーム位置・シムは
      // x4_24_settings.dart の同種項目に準拠。
      for (final position in armPositions) ...[
        numberSetting(
          key: '$end${position}UpperArmPosition',
          category: end,
          label: '$label アッパーアーム位置 $position',
          unit: 'mm',
          max: 10,
        ),
        numberSetting(
          key: '$end${position}LowerArmPosition',
          category: end,
          label: '$label ロワアーム位置 $position',
          unit: 'mm',
          max: 10,
        ),
      ],
      selectSetting(
        key: '${end}CasterAngle',
        category: end,
        label: '$label アッパーアーム位置（キャスター）',
        options: casterOptions,
      ),
      numberSetting(
        key: '${end}UprightTopShim',
        category: end,
        label: '$label アップライト上側シム',
        unit: 'mm',
        min: 0,
        max: 10,
        step: 0.5,
        defaultValue: '0',
      ),
      numberSetting(
        key: '${end}UprightLowerShim',
        category: end,
        label: '$label アップライト下側シム',
        unit: 'mm',
        min: 0,
        max: 10,
        step: 0.5,
        defaultValue: '0',
      ),
      numberSetting(
        key: '${end}RideHeight',
        category: end,
        label: '$label 車高',
        unit: 'mm',
        min: 3,
        max: 10,
        step: 0.1,
        defaultValue: '5',
      ),
      numberSetting(
        key: '${end}Camber',
        category: end,
        label: '$label キャンバー角',
        unit: 'degr.',
        min: -10,
        max: 10,
        step: 0.5,
        defaultValue: '-2',
      ),
      numberSetting(
        key: '${end}ToeAngle',
        category: end,
        label: '$label トー${end == 'front' ? 'アウト' : 'イン'}角',
        unit: 'degr.',
        min: -5,
        max: 5,
        step: 0.1,
        defaultValue: end == 'front' ? '-1' : '3',
      ),
      numberSetting(
        key: '${end}Droop',
        category: end,
        label: '$label ダウンストップ',
        unit: 'mm',
        min: -3,
        max: 10,
        step: 1,
        defaultValue: '0',
      ),
      textSetting(
        key: '${end}HubOffset',
        category: end,
        label: '$label アップライトオフセット',
        unit: 'mm',
      ),
      textSetting(
          key: '${end}Stabilizer', category: end, label: '$label スタビライザー'),
    ];

List<SettingItem> _damperSettings(String end, String label) {
  final category = '${end}Damper';
  return [
    textSetting(key: '${end}Piston', category: category, label: '$label ピストン'),
    textSetting(
      key: '${end}ShockCase',
      category: category,
      label: '$label ダンパーケース',
    ),
    textSetting(
      key: '${end}ShockOil',
      category: category,
      label: '$label ダンパーオイル',
    ),
    textSetting(key: '${end}Spring', category: category, label: '$label スプリング'),
    // 長さと取り付け位置の範囲・刻みは x4_24_settings.dart のダンパー長・マウントシムに準拠。
    numberSetting(
      key: '${end}DamperLength',
      category: category,
      label: '$label ダンパー長',
      unit: 'mm',
      min: 0,
      max: 50,
      step: 0.5,
      defaultValue: '8',
    ),
    numberSetting(
      key: '${end}ShockPosition',
      category: category,
      label: '$label ダンパー取り付け位置',
      unit: 'mm',
      min: 0,
      max: 10,
      step: 0.5,
      defaultValue: '0',
    ),
  ];
}

