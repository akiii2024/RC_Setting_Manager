List<SettingItem> _endSettings(String end, String label, String labelEn) {
  final isFront = end == 'front';
  final damper = '${end}Damper';
  return [
    // 抽出テキストの図に単位だけが印字された欄は、対象部位を特定できないため省略。
    // シートに範囲の記載がない角度・車高・ダウンストップ・スタビ径・シム類は
    // x4_24_settings.dart の同種項目の範囲と刻みを使用。
    numberSetting(
      key: '${end}Camber',
      category: end,
      label: '$label キャンバー角',
      labelEn: '$labelEn Camber Angle',
      unit: 'degr.',
      min: -10,
      max: 10,
      step: 0.5,
      defaultValue: '-2',
    ),
    numberSetting(
      key: '${end}ToeAngle',
      category: end,
      label: '$label トー角',
      labelEn: '$labelEn Toe Angle',
      unit: 'degr.',
      min: -5,
      max: 5,
      step: 0.1,
      defaultValue: isFront ? '-1' : '3',
    ),
    numberSetting(
      key: '${end}RideHeight',
      category: end,
      label: '$label 車高',
      labelEn: '$labelEn Ride Height',
      unit: 'mm',
      min: 3,
      max: 10,
      step: 0.1,
      defaultValue: '5',
    ),
    numberSetting(
      key: '${end}Droop',
      category: end,
      label: '$label ダウンストップ',
      labelEn: '$labelEn Downstop',
      unit: 'mm',
      min: -3,
      max: 10,
      step: 1,
    ),
    numberSetting(
      key: '${end}Stabilizer',
      category: end,
      label: '$label スタビライザー径',
      labelEn: '$labelEn Anti-roll Bar Diameter',
      unit: 'mm',
      min: 1.0,
      max: 3.0,
      step: 0.1,
