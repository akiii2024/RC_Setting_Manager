      labelEn: '$labelEn Diff Shims',
      unit: 'mm',
      max: 10,
      step: 0.5,
    ),
    // キャスター角は自由記入欄。X4 2024 は選択式のため数値制約を流用しない。
    textSetting(
      key: '${end}CasterAngle',
      category: end,
      label: '$label キャスター角',
      labelEn: '$labelEn Caster Angle',
      unit: 'degr.',
    ),
    selectSetting(
      key: '${end}ArbStiffener',
      category: end,
      label: '$label スタビライザースティフナー',
      labelEn: '$labelEn ARB Stiffener',
      options: const ['1/4', '1/2', '3/4', '1'],
    ),
    textSetting(
      key: '${end}SteeringArm',
      category: end,
      label: '$label ステアリングアーム',
      labelEn: '$labelEn Steering Arm',
      options: isFront ? const ['AM14LS'] : const ['AM23-R'],
    ),
    if (isFront)
      selectSetting(
        key: 'frontDrive',
        category: end,
        label: 'フロント ドライブ',
        labelEn: 'Front Drive',
        options: const ['SPOOL', 'DIFF'],
      )
    else
      textSetting(
        key: 'rearDrive',
        category: end,
        label: 'リヤ ドライブ',
        labelEn: 'Rear Drive',
      ),
    selectSetting(
      key: '${end}DrivePosition',
      category: end,
      label: '$label ドライブ位置',
      labelEn: '$labelEn Drive Position',
      options: const ['UP', 'DOWN'],
    ),
    textSetting(
      key: '${end}Diff',
      category: end,
      label: '$label デフオイル',
      labelEn: '$labelEn Diff Oil',
      unit: 'cSt',
    ),
    selectSetting(
      key: '${end}DamperType',
      category: damper,
      label: '$label ダンパー',
      labelEn: '$labelEn Damper',
      options: const ['D3'],
    ),
    selectSetting(
      key: '${end}PistonHole',
      category: damper,
      label: '$label ローター穴数',
      labelEn: '$labelEn Rotor Holes',
      options: const ['2'],
    ),
    selectSetting(
      key: '${end}DamperSpring',
      category: damper,
      label: '$label スプリング',
      labelEn: '$labelEn Spring',
      options: const ['STD', 'S'],
    ),
    selectSetting(
      key: '${end}DamperSrsRhs',
      category: damper,
      label: '$label SRS/RHS 配置',
      labelEn: '$labelEn SRS/RHS Arrangement',
      options: const ['I', 'II'],
    ),
    selectSetting(
      key: '${end}DamperPss',
      category: damper,
      label: '$label PSS 設定',
      labelEn: '$labelEn PSS Setup',
      options: const ['25%', '15%'],
    ),
    selectSetting(
      key: '${end}DamperDamping',
      category: damper,
      label: '$label 減衰特性',
      labelEn: '$labelEn Damping',
      options: const ['LINEAR', 'PROGRESSIVE'],
    ),
    selectSetting(
      key: '${end}DamperC45',
      category: damper,
      label: '$label C45',
      labelEn: '$labelEn C45',
      options: const ['YES', 'NO'],
    ),
    selectSetting(
      key: '${end}DamperSecondSpring',
      category: damper,
      label: '$label セカンドスプリング',
      labelEn: '$labelEn 2nd Spring',
      options: const ['SPR-P1'],
