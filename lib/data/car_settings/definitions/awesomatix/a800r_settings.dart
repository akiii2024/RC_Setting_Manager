List<SettingItem> _endSettings(String end, String label) {
  final isFront = end == 'front';
  final damper = '${end}Damper';
  return [
    // 抽出テキストの図に単位だけが印字された欄は、対象部位を特定できないため省略。
    // シートに範囲の記載がない角度・車高・ダウンストップ・スタビ径・シム類は
    // x4_24_settings.dart の同種項目の範囲と刻みを使用。
    numberSetting(
      key: '${end}Camber',
      category: end,
      label: '$label キャンバー角',
      unit: 'degr.',
      min: -10,
      max: 10,
      step: 0.5,
      defaultValue: '-2',
    ),
    numberSetting(
      key: '${end}ToeAngle',
      category: end,
      label: '$label トー角',
      unit: 'degr.',
      min: -5,
      max: 5,
      step: 0.1,
      defaultValue: isFront ? '-1' : '3',
    ),
    numberSetting(
      key: '${end}RideHeight',
      category: end,
      label: '$label 車高',
      unit: 'mm',
      min: 3,
      max: 10,
      step: 0.1,
      defaultValue: '5',
    ),
    numberSetting(
      key: '${end}Droop',
      category: end,
      label: '$label ダウンストップ',
      unit: 'mm',
      min: -3,
      max: 10,
      step: 1,
    ),
    numberSetting(
      key: '${end}Stabilizer',
      category: end,
      label: '$label スタビライザー径',
      unit: 'mm',
      min: 1.0,
      max: 3.0,
      step: 0.1,
      defaultValue: '1.2',
    ),
    numberSetting(
      key: '${end}LowerArmExtension',
      category: end,
      label: '$label ロワアーム延長',
      unit: 'mm',
      max: 10,
      step: 0.5,
    ),
    numberSetting(
      key: '${end}WheelSpacer',
      category: end,
      label: '$label ホイールスペーサー',
      unit: 'mm',
      max: 10,
      step: 0.5,
    ),
    numberSetting(
      key: '${end}DiffShim',
      category: end,
      label: '$label デフシム',
      unit: 'mm',
      max: 10,
      step: 0.5,
    ),
    // キャスター角は自由記入欄。X4 2024 は選択式のため数値制約を流用しない。
    textSetting(
      key: '${end}CasterAngle',
      category: end,
      label: '$label キャスター角',
      unit: 'degr.',
    ),
    selectSetting(
      key: '${end}ArbStiffener',
      category: end,
      label: '$label スタビライザースティフナー',
      options: const ['1/4', '1/2', '3/4', '1'],
    ),
    textSetting(
      key: '${end}SteeringArm',
      category: end,
      label: '$label ステアリングアーム',
      options: isFront ? const ['AM14LS'] : const ['AM23-R'],
    ),
    if (isFront)
      selectSetting(
        key: 'frontDrive',
        category: end,
        label: 'フロント ドライブ',
        options: const ['SPOOL', 'DIFF'],
      )
    else
      textSetting(key: 'rearDrive', category: end, label: 'リヤ ドライブ'),
    selectSetting(
      key: '${end}DrivePosition',
      category: end,
      label: '$label ドライブ位置',
      options: const ['UP', 'DOWN'],
    ),
    textSetting(
      key: '${end}Diff',
      category: end,
      label: '$label デフオイル',
      unit: 'cSt',
    ),
    selectSetting(
      key: '${end}DamperType',
      category: damper,
      label: '$label ダンパー',
      options: const ['D3'],
    ),
    selectSetting(
      key: '${end}PistonHole',
      category: damper,
      label: '$label ローター穴数',
      options: const ['2'],
    ),
    selectSetting(
      key: '${end}DamperSpring',
      category: damper,
      label: '$label スプリング',
      options: const ['STD', 'S'],
    ),
    selectSetting(
      key: '${end}DamperSrsRhs',
      category: damper,
      label: '$label SRS/RHS 配置',
      options: const ['I', 'II'],
    ),
    selectSetting(
      key: '${end}DamperPss',
      category: damper,
      label: '$label PSS 設定',
      options: const ['25%', '15%'],
    ),
    selectSetting(
      key: '${end}DamperDamping',
      category: damper,
      label: '$label 減衰特性',
      options: const ['LINEAR', 'PROGRESSIVE'],
    ),
    selectSetting(
      key: '${end}DamperC45',
      category: damper,
      label: '$label C45',
      options: const ['YES', 'NO'],
    ),
    selectSetting(
      key: '${end}DamperSecondSpring',
      category: damper,
      label: '$label セカンドスプリング',
      options: const ['SPR-P1'],
    ),
    textSetting(
      key: '${end}ShockOil',
      category: damper,
      label: '$label ダンパーオイル',
      unit: 'cSt',
    ),
  ];
}

