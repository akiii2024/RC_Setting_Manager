List<SettingItem> _sideSettings(String end, String label) {
  final isFront = end == 'front';
  final side = isFront ? 'Front' : 'Rear';
  return [
    // 範囲の記載がない車高・ダウンストップ・キャンバー・スタビライザー・
    // サスマウントシムは x4_24_settings.dart の同種項目に準拠。
    numberSetting(
      key: '${end}GroundClearance',
      category: end,
      label: '$label 車高',
      labelEn: '$side Ride Height',
      unit: 'mm',
      min: 3,
      max: 10,
      step: 0.1,
      defaultValue: isFront ? '5' : '5.5',
    ),
    numberSetting(
      key: '${end}Droop',
      category: end,
      label: '$label ダウンストップ',
      labelEn: '$side Downstop',
      unit: 'mm',
      min: -3,
      max: 10,
      step: 1,
      defaultValue: isFront ? '5' : '4',
    ),
    numberSetting(
      key: '${end}CamberAngle',
      category: end,
      label: '$label キャンバー角',
      labelEn: '$side Camber',
      unit: 'degr.',
      min: -10,
      max: 10,
      step: 0.5,
      defaultValue: '-2',
    ),
    numberSetting(
      key: '${end}Stabilizer',
      category: end,
      label: '$label スタビライザー',
      labelEn: '$side Anti-roll Bar',
      unit: 'mm',
      min: 1.0,
      max: 3.0,
      step: 0.1,
      defaultValue: '1.3',
    ),
    selectSetting(
      key: '${end}ArmLength',
      category: end,
      label: '$label サスアーム長',
      labelEn: '$side Suspension Arm Length',
      options: const ['SHORT', 'LONG'],
    ),
    selectSetting(
      key: '${end}Arms',
      category: end,
      label: '$label サスアーム硬度',
      labelEn: '$side Suspension Arm Hardness',
      options: const ['HARD', 'STD', 'SOFT'],
      defaultValue: 'STD',
    ),
    selectSetting(
      key: '${end}HubOffset',
      category: end,
      label: '$label ハブオフセット',
      labelEn: '$side Hub Offset',
      options: const ['-0.75mm', '0 mm', '+0.75mm'],
      defaultValue: '0 mm',
    ),
    selectSetting(
      key: '${end}Belt',
      category: end,
      label: '$label ベルト',
      labelEn: '$side Belt',
      options: const ['STD', 'SOFT'],
    ),
    selectSetting(
      key: '${end}DiffPositionHeight',
      category: end,
      label: '$label デフ高さ',
      labelEn: '$side Diff Height',
      options: const ['HIGH', 'LOW'],
    ),
    for (final mount in isFront ? const ['FF', 'FR'] : const ['RF', 'RR']) ...[
      selectSetting(
        key: '$end${mount}SusMountInsert',
        category: end,
        label: '$label $mount サスマウントインサート',
        labelEn: '$side Suspension Mount Insert ($mount)',
        options: const ['0', '0.5', '1.0', '1.5', '2.0'],
      ),
      selectSetting(
        key: '$end${mount}SusMountMaterial',
        category: end,
        label: '$label $mount サスマウント材質',
        labelEn: '$side Suspension Mount Material ($mount)',
        options: const ['Alu', 'Brass'],
      ),
      numberSetting(
        key: '$end${mount}SusMountSpacer',
        category: end,
        label: '$label $mount サスマウントシム',
        labelEn: '$side Suspension Mount Shim ($mount)',
        unit: 'mm',
        min: 0,
        max: 10,
        // リヤのシート基準値 0.8 mm を入力できる刻みにする。
        step: isFront ? 0.5 : 0.1,
        defaultValue: isFront ? '0.5' : '0.8',
      ),
    ],
  ];
}

